#UI and input handling for minesweeper game
import pygame
from minigame import Minigame
from minesweeperLogic import Minesweeper as Board
from minesweeperLogic import WIN, LOSS, FLAG, MINE, EXPLODED_MINE, UNVISITED

import random

CELL_SIZE = 32
GRID_X, GRID_Y = 240, 50 

#Define the colors for each number
NUMBER_COLORS = {1: (40, 90, 220), 
                 2: (40, 150, 60), 
                 3: (220, 50, 50), 
                 4: (60, 40, 160),
                 5: (150, 40, 40), 
                 6: (30, 150, 150), 
                 7: (30, 30, 30), 
                 8: (120, 120, 120),
                 }


class Minesweeper(Minigame):
    title = "Minesweeper"
    instructions = "Left click to reveal cell, right click to flag.\nClick a cell to start."

    def __init__(self, game, difficulty, seed):
        super().__init__(game, difficulty, seed)
        self.font = pygame.font.Font(None, 28)
        #Set the number of mines based on the current difficulty
        self.mineCount = min(15 + 2 * (self.difficulty-1), 30)
        self.board = None
        if not self.game.session.isSingle():
            self.instructions = "Left click to reveal cell, right click to flag.\nStarting cell is predetermined."
            rng = random.Random(seed)
            #Use the seed to calculate a random starting location that is the same for both players
            startX, startY = rng.randrange(10), rng.randrange(10)
            self.board = Board(startX, startY, self.mineCount, seed)
        self.time = max(60, 120 - ((self.difficulty-1)*10))

    #This method is used to count down a game timer
    def update(self, dt):
        if self.finished or self.board is None:
            return
        self.time -= dt
        #Case for time running out
        if self.time <=0:
            self.time = 0
            #Store the progress the player made
            self.result.progress = self.board.Progress() if self.board else 0
            self.finish(completed=False)
    #This method handles mouse click inputs 
    def handleEvent(self, event):
        if self.finished or event.type != pygame.MOUSEBUTTONDOWN:
            return
        x = (event.pos[0] - GRID_X) // CELL_SIZE
        y = (event.pos[1] - GRID_Y) // CELL_SIZE
        if not (0 <= x < 10 and 0 <= y < 10):
            return

        #Left click
        if event.button == 1:
            if self.board is None:
                self.board = Board(x, y, self.mineCount, self.seed)
            outcome = self.board.Outcome(x, y)
            if outcome in (WIN, LOSS):
                self.result.progress = self.board.Progress()
                self.finish(completed=(outcome == WIN))
        #Right click
        elif event.button == 3 and self.board is not None:
            self.board.Flag(x, y)

    #Draw the board UI
    def draw(self, surface):
        surface.fill((30, 30, 50))
        #Case for before first user input
        if self.board is None:
            status = "Click any cell to start"
        #Case for game ending
        elif self.finished:
            #On game end, show the user a win message or the percent of the cells they opened
            status = "Cleared!" if self.result.completed else f"Progress: {self.result.progress:.0%}"
        else:
            #Show the mines remaining
            status = f"Mines Remaining: {self.board.RemainingMines()}    Time: {self.time:.0f}"
        text = self.font.render(status, True, (255, 255, 255))
        surface.blit(text, text.get_rect(center=(GRID_X + 5 * CELL_SIZE, GRID_Y - 22)))

        #Loop for drawing all the cells
        #Code below was generated by Claude
        for x in range(10):
            for y in range(10):
                cell = UNVISITED if self.board is None else self.board.visited[x][y]
                rect = pygame.Rect(GRID_X + x * CELL_SIZE, GRID_Y + y * CELL_SIZE, CELL_SIZE, CELL_SIZE)
                cx, cy = rect.center

                if cell is UNVISITED or cell == FLAG:
                    color = (100, 115, 155)
                #Set the cell color to red if the user clicks on a mine
                elif cell == EXPLODED_MINE:
                    color = (220, 70, 70)
                else:
                    color = (215, 215, 225)
                pygame.draw.rect(surface, color, rect.inflate(-2, -2), border_radius=4)

                #Code for drawing a flag 
                if cell == FLAG:
                    pygame.draw.rect(surface, (30, 30, 30), (cx - 7, cy + 7, 14, 3))
                    pygame.draw.line(surface, (30, 30, 30), (cx - 1, cy - 9), (cx - 1, cy + 7), 2)
                    pygame.draw.polygon(surface, (230, 50, 50), [(cx, cy - 9), (cx + 9, cy - 5), (cx, cy - 1)])
                #Draw mines
                elif cell in (MINE, EXPLODED_MINE):
                    for dx, dy in ((10, 0), (0, 10), (7, 7), (7, -7)):
                        pygame.draw.line(surface, (20, 20, 20), (cx - dx, cy - dy), (cx + dx, cy + dy), 2)
                    pygame.draw.circle(surface, (20, 20, 20), (cx, cy), 7)
                #Draw numbers
                elif cell is not UNVISITED and cell > 0:
                    number = self.font.render(str(cell), True, NUMBER_COLORS[cell])
                    surface.blit(number, number.get_rect(center=(cx, cy)))